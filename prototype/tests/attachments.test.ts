import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'
import { parseAttachment } from '../src/lib/attachments'
import { officeZip,docxFiles,xlsxFiles,pptxFiles } from './attachment-fixtures'
describe('isolated bounded learner file readers',()=>{
  it('reads UTF-8 bilingual text and quoted CSV cells without executing formula-like content',async()=>{
    expect((await parseAttachment(Buffer.from('Provided records support the proposed next check. 請核實缺失記錄及所有分母。'),'txt')).extractedText).toContain('請核實')
    const csv=await parseAttachment(Buffer.from('name,note\nanalyst,"comma, quote and =IMPORTDATA(https://invalid.example)"'),'csv')
    expect(csv.extractedText).toContain('=IMPORTDATA')
    expect(csv.limitations[0]).toContain('not executed')
  })
  it('reads real Office ZIP structures, preserves slide order and shows saved formula results',async()=>{
    const docx=await parseAttachment(officeZip(docxFiles),'docx')
    expect(docx.extractedText).toContain('Owner: analyst')
    const xlsx=await parseAttachment(officeZip(xlsxFiles),'xlsx')
    expect(xlsx.extractedText).toContain('A1: Evidence reviewed')
    expect(xlsx.extractedText).toContain('C1: formula B1/2 | cached result 6')
    expect(xlsx.limitations.some(t=>t.includes('not calculated'))).toBe(true)
    const pptx=await parseAttachment(officeZip(pptxFiles),'pptx')
    expect(pptx.extractedText.indexOf('First slide')).toBeLessThan(pptx.extractedText.indexOf('Second slide'))
    expect(pptx.substantiveCharacters).toBeLessThan(pptx.extractedText.length)
  })
  it('reads actual Office files generated by pptxgenjs, docx and openpyxl',async()=>{
    for(const format of ['xlsx','pptx','docx'] as const){
      const file=readFileSync(resolve(process.cwd(),`tests/fixtures/readable-work.${format}`))
      const read=await parseAttachment(file,format)
      expect(read.extractedText).toContain('Verify all denominators')
      expect(read.substantiveCharacters).toBeGreaterThan(50)
    }
  })
  it('rejects active external templates and ambiguous relationships while ignoring passive source links',async()=>{
    const external='<Relationships><Relationship Id="remote" Target="https://invalid.example/template.dotm" TargetMode="External" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/attachedTemplate"/></Relationships>'
    await expect(parseAttachment(officeZip({...docxFiles,'word/_rels/document.xml.rels':external}),'docx')).rejects.toMatchObject({code:'unsafe_file'})
    const passive=external.replace('attachedTemplate','hyperlink').replace('template.dotm','source')
    expect((await parseAttachment(officeZip({...docxFiles,'word/_rels/document.xml.rels':passive}),'docx')).extractedText).toContain('Owner: analyst')
    const duplicate='<Relationships><Relationship Id="rId1" Target="worksheets/sheet1.xml"/><Relationship Id="rId1" Target="worksheets/sheet2.xml"/></Relationships>'
    await expect(parseAttachment(officeZip({...xlsxFiles,'xl/_rels/workbook.xml.rels':duplicate}),'xlsx')).rejects.toMatchObject({code:'invalid_file'})
  })
  it('validates XML CRC and preserves explicit text separators, hidden-sheet and formula limitations',async()=>{
    const badCrc=officeZip(docxFiles)
    const central=badCrc.indexOf(Buffer.from([0x50,0x4b,0x01,0x02]))
    badCrc.writeUInt32LE(0,central+16)
    await expect(parseAttachment(badCrc,'docx')).rejects.toMatchObject({code:'invalid_file'})
    const docx=await parseAttachment(officeZip({...docxFiles,'word/document.xml':'<document><p><r><t>First</t></r><r><tab/></r><r><t>column</t><br/><t>Next line</t></r></p></document>'}),'docx')
    expect(docx.extractedText).toBe('First\tcolumn\nNext line')
    const workbook=xlsxFiles['xl/workbook.xml'].replace('sheetId="1"','sheetId="1" state="veryHidden"')
    const sheet=xlsxFiles['xl/worksheets/sheet1.xml'].replace('<f>B1/2</f>','<f t="shared" si="0"/>')
    const xlsx=await parseAttachment(officeZip({...xlsxFiles,'xl/workbook.xml':workbook,'xl/worksheets/sheet1.xml':sheet}),'xlsx')
    expect(xlsx.extractedText).toContain('[hidden]')
    expect(xlsx.extractedText).toContain('shared or array formula reference, not expanded')
    expect(xlsx.limitations.join(' ')).toContain('not expanded')
  })
  it('rejects malformed, mislabeled, binary, oversized and empty documents',async()=>{
    for(const [bytes,format] of [[Buffer.from('not a zip'),'xlsx'],[officeZip(docxFiles),'pptx'],[Buffer.from([0,1,2]),'txt'],[Buffer.alloc(0),'txt']] as const) await expect(parseAttachment(bytes,format)).rejects.toBeTruthy()
    await expect(parseAttachment(Buffer.alloc(5*1024*1024+1),'txt')).rejects.toMatchObject({code:'file_too_large'})
  })
  it('rejects path traversal, XML entities, macros, encrypted archives and zip bombs',async()=>{
    for(const bytes of [
      officeZip({...docxFiles,'../escape.xml':'<unsafe/>'}),
      officeZip({...docxFiles,'word/document.xml':'<!DOCTYPE document [<!ENTITY x SYSTEM "file:///run/secrets/deepseek_key">]><document>&x;</document>'}),
      officeZip({...docxFiles,'word/vbaProject.bin':'macro'}),
      officeZip(docxFiles,{encrypted:true}),
      officeZip(docxFiles,{declaredSize:31*1024*1024}),
      officeZip({...docxFiles,'word/document.xml':`<document>${'x'.repeat(2*1024*1024)}</document>`}),
    ])await expect(parseAttachment(bytes,'docx')).rejects.toBeTruthy()
  })
  it('rejects a huge extracted handover and does not count generated sheet headings as substance',async()=>{
    await expect(parseAttachment(Buffer.from('x'.repeat(24001)),'txt')).rejects.toMatchObject({code:'extraction_too_large'})
    await expect(parseAttachment(officeZip({...xlsxFiles,'xl/worksheets/sheet1.xml':'<worksheet><sheetData/></worksheet>'}),'xlsx')).rejects.toMatchObject({code:'invalid_file'})
  })
})
