import {afterEach,describe,expect,it,vi} from 'vitest'
import {generationTiming,providerDeadlineMs} from '../src/lib/provider-timing'
afterEach(()=>vi.unstubAllEnvs())
describe('body-inclusive generation deadlines and reservation lifetimes',()=>{
 it('permits a bounded 150 second offline generation deadline only with the offline provider limit',()=>{
  vi.stubEnv('CURRICULUM_OFFLINE_TIMEOUT_MS','150000')
  vi.stubEnv('CURRICULUM_OFFLINE_PROVIDER_LIMIT','6')
  expect(providerDeadlineMs('author')).toBe(150000)
  expect(providerDeadlineMs('review')).toBe(150000)
  expect(providerDeadlineMs('grade')).toBe(45000)
  expect(generationTiming()).toEqual({workMs:300000,leaseMs:320000,lockMs:330000,requestMs:350000})
  vi.stubEnv('CURRICULUM_OFFLINE_PROVIDER_LIMIT','')
  vi.stubEnv('AI_GENERATION_AUTHOR_TIMEOUT_MS','45000')
  vi.stubEnv('AI_GENERATION_REVIEW_TIMEOUT_MS','45000')
  expect(providerDeadlineMs('author')).toBe(45000)
  expect(providerDeadlineMs('review')).toBe(45000)
 })
 it('does not extend an offline deadline beyond its bound or production deadlines beyond 90 seconds',()=>{
  vi.stubEnv('CURRICULUM_OFFLINE_TIMEOUT_MS','150001')
  vi.stubEnv('CURRICULUM_OFFLINE_PROVIDER_LIMIT','6')
  vi.stubEnv('AI_GENERATION_AUTHOR_TIMEOUT_MS','45000')
  expect(providerDeadlineMs('author')).toBe(45000)
  vi.stubEnv('AI_GENERATION_REVIEW_TIMEOUT_MS','150000')
  expect(()=>providerDeadlineMs('review')).toThrow('configuration')
 })
 it('covers the author followed by three parallel reviews with explicit publication and request margins',()=>{
  vi.stubEnv('CURRICULUM_OFFLINE_TIMEOUT_MS','')
  vi.stubEnv('AI_GENERATION_AUTHOR_TIMEOUT_MS','45000')
  vi.stubEnv('AI_GENERATION_REVIEW_TIMEOUT_MS','45000')
  expect(generationTiming()).toEqual({workMs:90000,leaseMs:110000,lockMs:120000,requestMs:140000})
 })
 it('extends lock and lease together for bounded longer generation while grading remains45 seconds',()=>{
  vi.stubEnv('CURRICULUM_OFFLINE_TIMEOUT_MS','')
  vi.stubEnv('AI_GENERATION_AUTHOR_TIMEOUT_MS','90000')
  vi.stubEnv('AI_GENERATION_REVIEW_TIMEOUT_MS','90000')
  expect(generationTiming()).toEqual({workMs:180000,leaseMs:200000,lockMs:210000,requestMs:230000})
  expect(providerDeadlineMs('grade')).toBe(45000)
 })
 it('rejects invalid production deadline settings and includes a valid offline override in bounds',()=>{
  vi.stubEnv('CURRICULUM_OFFLINE_TIMEOUT_MS','')
  vi.stubEnv('AI_GENERATION_REVIEW_TIMEOUT_MS','90001')
  expect(()=>generationTiming()).toThrow('configuration')
  vi.stubEnv('CURRICULUM_OFFLINE_TIMEOUT_MS','90000')
  expect(generationTiming().leaseMs).toBe(200000)
  expect(providerDeadlineMs('grade')).toBe(45000)
 })
 it('bounds one targeted repair as two sequential complete rounds while grading stays independent',()=>{
  vi.stubEnv('CURRICULUM_OFFLINE_TIMEOUT_MS','')
  vi.stubEnv('AI_GENERATION_AUTHOR_TIMEOUT_MS','45000')
  vi.stubEnv('AI_GENERATION_REVIEW_TIMEOUT_MS','90000')
  vi.stubEnv('AI_GENERATION_REPAIR_ATTEMPTS','1')
  expect(generationTiming()).toEqual({workMs:270000,leaseMs:290000,lockMs:300000,requestMs:320000})
  expect(providerDeadlineMs('grade')).toBe(45000)
  vi.stubEnv('AI_GENERATION_REPAIR_ATTEMPTS','2')
  expect(()=>generationTiming()).toThrow('repair configuration')
 })
})
